/**
 * seed-documents.js — Upload sample documents to Pinata and print real CIDs.
 *
 * Run:  node src/seed-documents.js
 *
 * This creates simple text/JSON documents for each project and pins them
 * to your Pinata account so the IPFS CIDs are real and accessible.
 */
require('dotenv').config();
const axios = require('axios');
const FormData = require('form-data');

const PINATA_PIN_URL = 'https://api.pinata.cloud/pinning/pinJSONToIPFS';
const PINATA_PIN_FILE_URL = 'https://api.pinata.cloud/pinning/pinFileToIPFS';

function getAuthHeaders() {
    const jwt = process.env.PINATA_JWT;
    if (jwt && jwt !== 'your_pinata_jwt') {
        return { Authorization: `Bearer ${jwt}` };
    }
    const apiKey = process.env.PINATA_API_KEY;
    const secretKey = process.env.PINATA_SECRET_KEY;
    if (apiKey && secretKey && apiKey !== 'your_pinata_api_key') {
        return { pinata_api_key: apiKey, pinata_secret_api_key: secretKey };
    }
    throw new Error('Pinata API keys not configured in .env');
}

async function pinJSON(name, jsonContent) {
    const headers = getAuthHeaders();
    const body = {
        pinataContent: jsonContent,
        pinataMetadata: {
            name,
            keyvalues: { app: 'govfund-nepal', type: 'seed-document' },
        },
        pinataOptions: { cidVersion: 0 },
    };

    const res = await axios.post(PINATA_PIN_URL, body, {
        headers: { ...headers, 'Content-Type': 'application/json' },
        timeout: 30000,
    });
    return res.data.IpfsHash;
}

async function pinTextFile(name, textContent) {
    const headers = getAuthHeaders();
    const formData = new FormData();
    const buffer = Buffer.from(textContent, 'utf-8');
    formData.append('file', buffer, { filename: name, contentType: 'text/plain' });
    formData.append('pinataMetadata', JSON.stringify({
        name,
        keyvalues: { app: 'govfund-nepal', type: 'seed-document' },
    }));
    formData.append('pinataOptions', JSON.stringify({ cidVersion: 0 }));

    const res = await axios.post(PINATA_PIN_FILE_URL, formData, {
        maxBodyLength: Infinity,
        timeout: 60000,
        headers: { ...formData.getHeaders(), ...headers },
    });
    return res.data.IpfsHash;
}

