// Build GeoJSON FeatureCollection
function buildFeatureCollection() {
  const features = Object.entries(provincePolygons).map(([id, coords]) => {
    const numId = Number(id);
    const style = PROVINCE_STYLES[numId];
    return {
      type: 'Feature',
      properties: {
        id: numId,
        name: style.name,
        nameNe: style.nameNe,
        capital: style.capital,
        capitalNe: style.capitalNe,
        fill: style.fill,
      },
      geometry: {
        type: 'Polygon',
        // GeoJSON polygons: array of rings, first ring = exterior
        coordinates: [coords],
      },
    };
  });

  return {
    type: 'FeatureCollection',
    features,
  };
}

export const nepalGeoJSON = buildFeatureCollection();

